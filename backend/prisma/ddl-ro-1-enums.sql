DO $$ BEGIN
  CREATE TYPE "MetodoAnaliseRo" AS ENUM (
    'CINCO_PORQUES', 'ISHIKAWA', 'PARETO', 'FMEA', 'OITO_D',
    'TESTE_REPRODUCAO', 'ANALISE_DADOS', 'AUDITORIA', 'OUTRO'
  );
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE "StatusAcaoRo" AS ENUM (
    'NAO_INICIADA', 'EM_ANDAMENTO', 'CONCLUIDA', 'ATRASADA', 'CANCELADA'
  );
