-- R.O - Gestao de Reclamacoes da Qualidade: enums.
-- As listas vem das validacoes da planilha
-- "especificacao_controle_reclamacoes_qualidade.xlsx".

-- O R.O entra como o 8o modulo da grade de acesso.
ALTER TYPE "ModuloSistema" ADD VALUE IF NOT EXISTS 'RO';

DO $$ BEGIN
  CREATE TYPE "CompletudeSacRo" AS ENUM ('SIM', 'NAO', 'PARCIAL');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE "AceiteRo" AS ENUM ('SIM', 'NAO', 'AGUARDANDO');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE "SimNaoRo" AS ENUM ('SIM', 'NAO');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE "ClassificacaoRo" AS ENUM (
    'DEFEITO_FUNCIONAL', 'FALHA_DESEMPENHO', 'PROBLEMA_DIMENSIONAL',
    'MATERIAL_INCORRETO', 'QUANTIDADE_INCORRETA', 'EMBALAGEM', 'DOCUMENTACAO',
    'MONTAGEM_INSTALACAO', 'SOFTWARE_COMUNICACAO', 'ENTREGA_LOGISTICA',
    'SEGURANCA', 'BEM_ESTAR_ANIMAL', 'MEIO_AMBIENTE', 'OUTRO'
  );
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE "ProcedenciaRo" AS ENUM (
    'PROCEDENTE', 'PARCIALMENTE_PROCEDENTE', 'NAO_PROCEDENTE', 'INCONCLUSIVA'
  );
