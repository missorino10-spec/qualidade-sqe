DO $$ BEGIN
  CREATE TYPE "AreaResponsavelRo" AS ENUM (
    'QUALIDADE_PRODUCAO', 'SQE', 'SQD', 'ENGENHARIA', 'LOGISTICA',
    'SERVICO_ASSISTENCIA', 'EQUIPE_MULTIFUNCIONAL'
  );
